"""Compile our trained JSON trees into ordinary Python branches, offline.

Avoids tree traversal/array-index overhead within the one-millisecond path.
No eval, exec or code generation occurs during gameplay.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    source = (ROOT / "assets/equity.json").read_bytes()
    model = json.loads(source)
    scale = 10_000_000
    offset = 1 << 21
    trees = model['trees']
    assert len(trees) < 1000

    def packed(values, bias=0):
        values = [round(v * scale) + bias for v in values]
        assert all(0 <= v < 1 << 32 for v in values)
        return sum(v << (32*i) for i, v in enumerate(values))

    lines = ['"""Generated by tools/compile_model.py from our original equity model."""',
             f'MODEL_SHA256 = "{hashlib.sha256(source).hexdigest()}"', '', 'def predict(x):']
    lines.append(f'    v = {packed(model["base"])}')

    def node(nodes, i, indent):
        f, t, left, right, *values = nodes[i]
        spaces = '    ' * indent
        if f < 0:
            # Eight fixed-point outputs occupy independent 32-bit lanes of
            # one 256-bit integer. Offset makes each contribution positive;
            # lane totals cannot overflow under the checked model bounds.
            # One integer addition replaces eight Python float additions.
            lines.append(f'{spaces}v += {packed(values, offset)}')
        else:
            lines.append(f'{spaces}if x[{f}] <= {t}:')
            node(nodes, left, indent + 1)
            lines.append(f'{spaces}else:')
            node(nodes, right, indent + 1)

    for k in range(8):
        maximum = round(model['base'][k] * scale)
        for tree in trees:
            maximum += max(round(n[4+k] * scale) + offset for n in tree if n[0] < 0)
        assert maximum < 1 << 32, 'packed output lane would overflow'
    for tree in trees:
        node(tree, 0, 1)
    lines.append('    return (')
    for k in range(8):
        lines.append(f'        min(1.0, max(0.0, (((v >> {32*k}) & 4294967295) - {len(trees)*offset}) / {scale})),')
    lines.append('    )')
    dest = ROOT / "bot/compiled_model.py"
    dest.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Wrote {dest.name}: {dest.stat().st_size:,} bytes; {len(model["trees"])} trees')


if __name__ == "__main__":
    main()
