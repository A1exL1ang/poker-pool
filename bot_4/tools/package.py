"""Build a small, allowlisted local delivery archive. Never submits it."""
import hashlib
import ast
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parent.parent


def main():
    out = ROOT / 'dist'
    out.mkdir(exist_ok=True)

    def without_relative_imports(path):
        source = (ROOT/path).read_text(encoding='utf-8')
        lines = source.splitlines(keepends=True)
        omit = set()
        for node in ast.parse(source).body:
            if isinstance(node, ast.ImportFrom) and node.level:
                omit.update(range(node.lineno-1, node.end_lineno))
        return ''.join(line for i,line in enumerate(lines) if i not in omit)

    # Flatten only this project's own modules. The generated entry point needs
    # no package directory, data files, native code or filesystem reads.
    sections = ['"""Standalone bot_4; generated by tools/package.py. Local API, not official compatibility."""\n',
                without_relative_imports('bot/cards.py'),
                'PREFLOP = ' + repr(json.loads((ROOT/'assets/preflop.json').read_text())) + '\n',
                without_relative_imports('bot/compiled_model.py'),
                without_relative_imports('bot/interface.py'),
                without_relative_imports('bot/icm.py'),
                without_relative_imports('bot/policy.py'),
                '\nif __name__ == "__main__":\n    import json, sys\n    bot = Agent()\n    for line in sys.stdin:\n        if line.strip():\n            print(json.dumps(bot.act(json.loads(line)), separators=(",", ":")), flush=True)\n']
    standalone = '\n\n'.join(sections).encode('utf-8')
    (out/'bot_4.py').write_bytes(standalone)
    names = ['agent.py', 'README.md', 'examples/decision.json', 'assets/preflop.json', 'assets/equity.json',
             'bot/__init__.py', 'bot/cards.py', 'bot/model.py', 'bot/compiled_model.py',
             'bot/interface.py', 'bot/icm.py', 'bot/policy.py']
    contents = {name: (ROOT / name).read_bytes() for name in names}
    contents['bot_4.py'] = standalone
    manifest = {'files': {name: {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
                          for name, data in contents.items()},
                'uncompressed_bytes': sum(map(len, contents.values())),
                'official_interface_compatible': False,
                'runtime_dependencies': 'Python 3.11+ standard library',
                'submitted': False}
    archive = out / 'bot_4.zip'
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name, data in contents.items():
            info = zipfile.ZipInfo(name, date_time=(2026, 11, 6, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, data)
    manifest['archive_bytes'] = archive.stat().st_size
    manifest['archive_sha256'] = hashlib.sha256(archive.read_bytes()).hexdigest()
    assert manifest['uncompressed_bytes'] < 100_000_000
    # Isolated extraction and import checks that no development-only package
    # or working-directory-relative asset is required. CWD stays this workspace.
    with tempfile.TemporaryDirectory(prefix='package-check-', dir=ROOT / 'evidence') as directory:
        assert Path(directory).resolve().is_relative_to((ROOT / 'evidence').resolve())
        with zipfile.ZipFile(archive) as z:
            z.extractall(directory)
        code = "import sys,json; sys.path.insert(0,sys.argv[1]); from agent import Agent; s=json.load(open(sys.argv[1]+'/examples/decision.json')); a=Agent().act(s); assert a['action']=='raise'; print(json.dumps(a))"
        test = subprocess.run([sys.executable, '-I', '-c', code, directory], cwd=ROOT,
                              text=True, capture_output=True, check=True)
        manifest['isolated_package_smoke'] = json.loads(test.stdout)
        # Check a sequence of public observations, preserving within-table
        # state, against the modular bot, not merely one opening action.
        sys.path.insert(0, str(ROOT))
        from agent import Agent
        observations = ROOT/'evidence/observations.jsonl'
        lines = observations.read_text().splitlines()[:500] if observations.exists() else [(ROOT/'examples/decision.json').read_text()]
        reference = Agent()
        expected = [reference.act(json.loads(line)) for line in lines]
        test = subprocess.run([sys.executable, '-I', str(Path(directory)/'bot_4.py')], cwd=ROOT,
                              input='\n'.join(lines)+'\n', text=True, capture_output=True, check=True)
        actual = [json.loads(line) for line in test.stdout.splitlines()]
        assert actual == expected, 'standalone and modular policies diverged'
        manifest['standalone_parity_observations'] = len(lines)
    manifest['standalone_bytes'] = len(standalone)
    manifest['standalone_sha256'] = hashlib.sha256(standalone).hexdigest()
    validation = ROOT/'evidence/validation_run.json'
    if validation.exists():
        validated = json.loads(validation.read_text())
        assert validated['passed']
        for name, expected in validated['source_sha256'].items():
            assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest() == expected, f'{name} changed after validation'
        manifest['source_matched_validation'] = True
        manifest['validation_report_sha256'] = hashlib.sha256(validation.read_bytes()).hexdigest()
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=2))
    print(json.dumps({k:v for k,v in manifest.items() if k!='files'}, indent=2))


if __name__ == '__main__':
    main()
