"""Compile exported numeric regression trees to a stdlib-only Python function.

Generated code contains numbers and fixed variable names only, never input text.
The source JSON SHA-256 is embedded and checked by bot.equity at import.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path


def compile_model(source, output):
    raw = Path(source).read_bytes()
    model = json.loads(raw)
    nf = int(model['feature_count'])
    lines = ['"""Generated by training/compile_model.py; original numeric equity trees."""',
             'MODEL_SHA256 = ' + repr(hashlib.sha256(raw).hexdigest()),
             'FEATURE_VERSION = ' + str(int(model['feature_version'])),
             '', 'def predict(f):',
             '    ' + ', '.join('f' + str(i) for i in range(nf)) + ' = f',
             '    v = ' + repr(float(model['baseline']))]
    def expression(tree, index):
        feat, value, left, right = tree[index]
        if feat == -1:
            return repr(float(value))
        feat = int(feat)
        if not 0 <= feat < nf:
            raise ValueError('Invalid feature index')
        # All features except the final range fraction / pressure are integral.
        # Integer cutpoints preserve branches and specialize faster on CPython.
        threshold = math.floor(value) if feat < nf - 2 else float(value)
        return '(' + expression(tree, int(left)) + ' if f' + str(feat) + ' <= ' + repr(threshold) + ' else ' + expression(tree, int(right)) + ')'
    for tree in model['trees']:
        lines.append('    v += ' + expression(tree, 0))
    lines.append('    return v')
    lines.append('')
    Path(output).write_text('\n'.join(lines))
    print('Compiled', len(model['trees']), 'trees;', Path(output).stat().st_size, 'source bytes')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--input', default='assets/equity_model.json')
    p.add_argument('--output', default='bot/_equity_compiled.py')
    a = p.parse_args()
    compile_model(a.input, a.output)
