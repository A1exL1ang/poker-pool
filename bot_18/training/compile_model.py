"""Compile trusted exported tree data to plain Python conditional expressions.

The generated module requires no compiler or third-party package at gameplay.
Its content hash binds it to the corresponding JSON asset and feature schema.
"""
import argparse
import hashlib
import json
from pathlib import Path


def expression(tree, index=0):
    node=tree[index]
    if node[0]<0:return repr(node[4])
    return "("+expression(tree,node[2])+" if f"+str(node[0])+" <= "+repr(node[1])+" else "+expression(tree,node[3])+")"


def compile_model(input_path, output_path):
    data=Path(input_path).read_bytes();model=json.loads(data)
    digest=hashlib.sha256(data).hexdigest()
    models=model.get("models",{"all":model})
    lines=["# Generated by training/compile_model.py from trusted local training data.",
           "FEATURE_VERSION = "+repr(model["feature_version"]),
           "MODEL_SHA256 = "+repr(digest),""]
    for key,part in models.items():
        lines.append("def predict_"+key+"(x):")
        lines.append("    "+", ".join("f"+str(i) for i in range(model["feature_count"]))+" = x")
        lines.append("    y = "+repr(part["base"]))
        for tree in part["trees"]:lines.append("    y += "+expression(tree))
        lines.extend(["    return y",""])
    lines.append("def predict(x):")
    if "all" in models:lines.append("    return predict_all(x)")
    else:
        for key in models:
            lines.append("    if x[0] == "+key+": return predict_"+key+"(x)")
        lines.append("    raise ValueError('invalid street feature')")
    source="\n".join(lines)+"\n"
    compile(source,str(output_path),"exec")
    Path(output_path).write_text(source,encoding="utf-8")
    return digest


if __name__=="__main__":
    p=argparse.ArgumentParser();p.add_argument("--model",required=True);p.add_argument("--output",required=True);args=p.parse_args()
    print(compile_model(args.model,args.output))
