"""Build and independently import an offline runtime ZIP inside this workspace."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import zipfile


CHECK = r'''
import builtins, json, pathlib, socket, sys, time
root = pathlib.Path(sys.argv[1]).resolve()
sys.path.insert(0, str(root))
def no_network(*args, **kwargs):
    raise AssertionError("network access forbidden in package verification")
socket.socket = no_network
socket.create_connection = no_network
socket.getaddrinfo = no_network
started = time.perf_counter_ns()
from agent import Agent
from pokerbot.interface import is_legal
bot = Agent(seed=20)
initialization = time.perf_counter_ns() - started
assert bot.estimator.model_loaded and bot.estimator.preflop_loaded
obs = json.loads((root / "example_observation.json").read_text())
original_open = builtins.open
def no_file_io(*args, **kwargs):
    raise AssertionError("unexpected gameplay file I/O")
builtins.open = no_file_io
started = time.perf_counter_ns()
action = bot.act(obs)
elapsed = time.perf_counter_ns() - started
builtins.open = original_open
assert is_legal(obs, action)
assert not bot.errors
print(json.dumps({"model_loaded":bot.estimator.model_loaded,"preflop_loaded":bot.estimator.preflop_loaded,
"action":action,"first_decision_us":elapsed/1000,"initialization_us":initialization/1000,
"network_disabled":True,"gameplay_builtin_open_disabled":True,"python":sys.version}))
'''


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="artifacts/bot_20.zip")
    parser.add_argument("--report", default="measurements/package_verification.json")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    paths = [root / "agent.py", root / "README.md"]
    paths.extend((root / "pokerbot").rglob("*.py"))
    paths.extend(p for p in (root / "pokerbot" / "assets").iterdir() if p.is_file())
    # This is our explicit local schema, generated by our own simulator.
    from simulator.engine import Hand
    obs = Hand([100, 2000, 2000, 2000, 2000, 2000, 2000, 2000], button=5,
               payouts=[.5, .3, .2, 0, 0, 0, 0, 0]).observation()
    paths = sorted(set(paths))
    output = root / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in paths:
            if not path.resolve().is_relative_to(root):
                raise ValueError("Refusing to package outside this bot workspace")
            archive.write(path, path.relative_to(root).as_posix())
        archive.writestr("example_observation.json", json.dumps(obs, indent=2) + "\n")
    if output.stat().st_size >= 100_000_000:
        raise AssertionError("Package exceeds conservative decimal100MB bound")
    # Unique local temporary destination; no existing directory is deleted.
    destination = Path(tempfile.mkdtemp(prefix="offline_check_", dir=root / "artifacts"))
    with zipfile.ZipFile(output) as archive:
        for name in archive.namelist():
            if not (destination / name).resolve().is_relative_to(destination.resolve()):
                raise ValueError("Invalid archive path")
        archive.extractall(destination)
    result = subprocess.run([sys.executable, "-I", "-c", CHECK, str(destination)],
                            cwd=destination, text=True, capture_output=True, check=True, timeout=30)
    check = json.loads(result.stdout)
    report = {"archive": str(output.relative_to(root)), "bytes": output.stat().st_size,
              "sha256": hashlib.sha256(output.read_bytes()).hexdigest(), "files": len(paths) + 1,
              "verification": check, "verification_directory": str(destination.relative_to(root)),
              "scope": "Fresh isolated Python import with no third-party gameplay dependencies. Local contract only; no official submission performed."}
    report_path = root / args.report
    report_path.parent.mkdir(exist_ok=True, parents=True)
    report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    return report


if __name__ == "__main__":
    main()
