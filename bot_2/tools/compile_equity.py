"""Compile trusted numeric tree data to ordinary Python conditional expressions.

No code generation occurs in the gameplay path. This reduces interpreter loop
and indexing overhead without any runtime binary or third-party dependency.
"""
import hashlib
import json
from pathlib import Path


def main():
    source = Path("assets/equity_model.json")
    model = json.loads(source.read_text())
    assert model["depth"] == 6
    lines = ["# Generated by tools/compile_equity.py; do not edit by hand.",
             "# Source SHA256: " + hashlib.sha256(source.read_bytes()).hexdigest(),
             "SOURCE_SHA256 = " + repr(hashlib.sha256(source.read_bytes()).hexdigest()),
             "def predict_raw(x, col):"]
    def expand(row):
        return (row[0], row[1], row[2], .5 * (row[2] + row[3]),
                row[3], .5 * (row[3] + row[4]), row[4])
    lines.append(f"    h = {model['base'][0]!r}")
    lines.append(f"    e = {expand(model['base'])!r}[col]")
    for tree in model["trees"]:
        def expr(node, depth):
            if depth == 6:
                return repr(expand(tuple(model["rate"] * v for v in tree["leaves"][node - 63])))
            left = expr(node * 2 + 1, depth + 1)
            right = expr(node * 2 + 2, depth + 1)
            return f"({left} if x[{tree['features'][node]}] <= {tree['thresholds'][node]} else {right})"
        lines.append("    v = " + expr(0, 0))
        lines.append("    h += v[0]")
        lines.append("    e += v[col]")
    lines.append("    return h, e")
    output = Path("pokerbot/_equity_compiled.py")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {output}, {output.stat().st_size} bytes")


if __name__ == "__main__":
    main()
