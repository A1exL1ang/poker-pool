"""Small, allocation-light Hold'em evaluator. Larger scores are better.

Cards are integers 0..51: (rank - 2) * 4 + suit, suits c/d/h/s.
This evaluator was written for this bot; it has no third-party dependency.
"""

RANKS = "23456789TJQKA"
SUITS = "cdhs"
BITS = tuple(1 << (c >> 2) for c in range(52))
STRAIGHT = [0] * 8192
TOP = [0] * 8192
TOP5 = [0] * 8192
for _mask in range(1, 8192):
    TOP[_mask] = _mask.bit_length()
    _bits = _mask
    _value = 0
    for _i in range(5):
        _r = _bits.bit_length()
        _value = (_value << 4) | _r
        if _r:
            _bits ^= 1 << (_r - 1)
    TOP5[_mask] = _value
    for _r in range(12, 3, -1):
        if (_mask >> (_r - 4)) & 31 == 31:
            STRAIGHT[_mask] = _r + 1
            break
    if not STRAIGHT[_mask] and _mask & 4111 == 4111:
        STRAIGHT[_mask] = 4


def parse_card(card):
    if isinstance(card, int) and not isinstance(card, bool) and 0 <= card < 52:
        return card
    if isinstance(card, str):
        card = card.strip().replace("10", "T")
        if len(card) == 2 and card[0].upper() in RANKS and card[1].lower() in SUITS:
            return RANKS.index(card[0].upper()) * 4 + SUITS.index(card[1].lower())
    raise ValueError("card must be 0..51 or a rank/suit string such as 'As'")


def card_name(card):
    return RANKS[card >> 2] + SUITS[card & 3]


def _evaluate_direct(cards):
    """Evaluate 5, 6, or 7 distinct integer cards; caller validates inputs."""
    seen = pairs = trips = quads = 0
    s0 = s1 = s2 = s3 = 0
    for c in cards:
        bit = BITS[c]
        quads |= trips & bit
        trips |= pairs & bit
        pairs |= seen & bit
        seen |= bit
        suit = c & 3
        if suit == 0:
            s0 |= bit
        elif suit == 1:
            s1 |= bit
        elif suit == 2:
            s2 |= bit
        else:
            s3 |= bit
    flush = s0 if s0.bit_count() >= 5 else s1 if s1.bit_count() >= 5 else s2 if s2.bit_count() >= 5 else s3 if s3.bit_count() >= 5 else 0
    if flush:
        straight_flush = STRAIGHT[flush]
        if straight_flush:
            return (8 << 20) | (straight_flush << 16)
    if quads:
        r = TOP[quads]
        return (7 << 20) | (r << 16) | (TOP[seen ^ (1 << (r - 1))] << 12)
    if trips:
        r = TOP[trips]
        rest = pairs ^ (1 << (r - 1))
        if rest:
            return (6 << 20) | (r << 16) | (TOP[rest] << 12)
    if flush:
        return (5 << 20) | TOP5[flush]
    straight = STRAIGHT[seen]
    if straight:
        return (4 << 20) | (straight << 16)
    if trips:
        r = TOP[trips]
        return (3 << 20) | (r << 16) | (TOP5[seen ^ (1 << (r - 1))] >> 4 & 0xFF00)
    if pairs:
        r = TOP[pairs]
        rest = pairs ^ (1 << (r - 1))
        if rest:
            q = TOP[rest]
            kicker = TOP[seen ^ (1 << (r - 1)) ^ (1 << (q - 1))]
            return (2 << 20) | (r << 16) | (q << 12) | (kicker << 8)
        return (1 << 20) | (r << 16) | (TOP5[seen ^ (1 << (r - 1))] >> 4 & 0xFFF0)
    return TOP5[seen]


# A rank-multiset lookup removes repeated counting from the hot path. The
# optional asset is generated by tools/build_rank_table.py from our evaluator.
# It contains only integers, never executable serialization.
RANK_CODE = tuple(1 << (3 * (c >> 2)) for c in range(52))
_RANK_TABLE = {}
try:
    from pathlib import Path
    import struct
    _rank_path = Path(__file__).resolve().parent.parent / "assets" / "ranks.bin"
    if _rank_path.exists():
        _rank_data = _rank_path.read_bytes()
        if _rank_data[:8] != b"B5RANK01" or (len(_rank_data) - 8) % 12:
            raise ValueError("invalid rank asset")
        _RANK_TABLE = dict(struct.iter_unpack("<QI", _rank_data[8:]))
        del _rank_data
except OSError:
    pass


def evaluate(cards):
    if not _RANK_TABLE:
        return _evaluate_direct(cards)
    key = 0
    s0 = s1 = s2 = s3 = 0
    for c in cards:
        key += RANK_CODE[c]
        bit = BITS[c]
        suit = c & 3
        if suit == 0:
            s0 |= bit
        elif suit == 1:
            s1 |= bit
        elif suit == 2:
            s2 |= bit
        else:
            s3 |= bit
    flush = s0 if s0.bit_count() >= 5 else s1 if s1.bit_count() >= 5 else s2 if s2.bit_count() >= 5 else s3 if s3.bit_count() >= 5 else 0
    if flush:
        straight_flush = STRAIGHT[flush]
        if straight_flush:
            return (8 << 20) | (straight_flush << 16)
        return (5 << 20) | TOP5[flush]
    return _RANK_TABLE[key]


class BoardEvaluator:
    """Reuse a public board while evaluating many different private pairs."""
    __slots__ = ("board", "key", "suits", "flush_suit", "flush_mask")

    def __init__(self, board):
        self.board = board
        self.key = sum(RANK_CODE[c] for c in board)
        suits = [0, 0, 0, 0]
        for c in board:
            suits[c & 3] |= BITS[c]
        self.suits = suits
        self.flush_suit = -1
        self.flush_mask = 0
        for s, mask in enumerate(suits):
            if mask.bit_count() >= 3:
                self.flush_suit = s
                self.flush_mask = mask
                break

    def add(self, card):
        result = object.__new__(BoardEvaluator)
        result.board = self.board + [card]
        result.key = self.key + RANK_CODE[card]
        result.suits = self.suits.copy()
        result.suits[card & 3] |= BITS[card]
        result.flush_suit = self.flush_suit
        result.flush_mask = self.flush_mask
        suit = card & 3
        if result.suits[suit].bit_count() >= 3:
            result.flush_suit = suit
            result.flush_mask = result.suits[suit]
        return result

    def pair(self, a, b):
        if not _RANK_TABLE:
            return _evaluate_direct(self.board + [a, b])
        if self.flush_mask:
            mask = self.flush_mask
            if a & 3 == self.flush_suit:
                mask |= BITS[a]
            if b & 3 == self.flush_suit:
                mask |= BITS[b]
            if mask.bit_count() >= 5:
                straight = STRAIGHT[mask]
                return (8 << 20) | (straight << 16) if straight else (5 << 20) | TOP5[mask]
        return _RANK_TABLE[self.key + RANK_CODE[a] + RANK_CODE[b]]


def hand_index(a, b):
    """Index into a 13x13 table: upper triangle suited, lower offsuit."""
    ra, rb = a >> 2, b >> 2
    hi, lo = max(ra, rb), min(ra, rb)
    return hi * 13 + lo if a & 3 == b & 3 else lo * 13 + hi


def hand_label(index):
    a, b = divmod(index, 13)
    if a == b:
        return RANKS[a] * 2
    return RANKS[max(a, b)] + RANKS[min(a, b)] + ("s" if a > b else "o")
